#!/usr/bin/env node
/**
 * Writes `apps/web/src/lib/google-fonts.generated.ts`: the families the theme
 * panel's font picker offers.
 *
 * Read from Google's own catalogue rather than typed out, so the list carries
 * the one fact the loader cannot guess: which weights a family actually ships.
 * The css2 API answers a request for a weight a family lacks with a 400 and no
 * CSS at all, so asking Bebas Neue for 600 would blank the heading instead of
 * faking a bold.
 *
 * Kept to latin families that ship a regular weight, without Noto's hundreds
 * of script-specific cuts (their two general faces stay), and capped by
 * popularity: the long tail is mostly faces nobody would set a form in.
 *
 *   node tooling/gen-google-fonts.mjs
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const LIMIT = 600;
/** The weights the chat surface actually sets: body, medium, semibold, bold. */
const USED = ["400", "500", "600", "700"];
const GENERAL_NOTO = new Set(["Noto Sans", "Noto Serif"]);
const CATEGORY = {
  "Sans Serif": "sans",
  Serif: "serif",
  Display: "display",
  Handwriting: "handwriting",
  Monospace: "mono",
};

const res = await fetch("https://fonts.google.com/metadata/fonts");
if (!res.ok) throw new Error(`catalogue: ${res.status}`);
const text = await res.text();
// Older responses carried an XSSI guard in front of the JSON.
const { familyMetadataList } = JSON.parse(text.replace(/^\)\]\}'\s*/, ""));

const rows = familyMetadataList
  .filter((f) => f.subsets.includes("latin") && (!f.isNoto || GENERAL_NOTO.has(f.family)) && f.fonts["400"] && CATEGORY[f.category])
  .sort((a, b) => a.popularity - b.popularity)
  .slice(0, LIMIT)
  .map((f) => [f.family, CATEGORY[f.category], USED.filter((w) => f.fonts[w]).map(Number)]);

const out = `/**
 * Generated by \`tooling/gen-google-fonts.mjs\` from Google Fonts' catalogue.
 * Do not edit by hand; rerun the script.
 *
 * [family, category, weights it ships out of 400/500/600/700], most popular first.
 */
export type GoogleFontCategory = "sans" | "serif" | "display" | "handwriting" | "mono";
export type GoogleFontRow = readonly [family: string, category: GoogleFontCategory, weights: readonly number[]];

export const GOOGLE_FONTS: readonly GoogleFontRow[] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join("\n")}
];
`;

const target = fileURLToPath(new URL("../apps/web/src/lib/google-fonts.generated.ts", import.meta.url));
writeFileSync(target, out);
console.log(`${rows.length} families → ${target}`);
